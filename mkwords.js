'use strict';
/*
 * mkwords.js: words.txt -> words.inc, the phrases as tables the program indexes by arithmetic.
 * It refuses a wrong count, an unknown token, a quote or backslash, and an entry that could
 * outgrow its four lines in the book (worst case over every combination).
 *
 *   wx.C.V      weather class 0-5, variant 0-3        24 lines, <= 40 characters
 *   lamp.L.V    lamp 0-3, variant 0-3                  16 lines, <= 38
 *   ship.K.V    seen, unseen, none; variant 0-3        12 lines, <= 70 expanded
 *   name.I time.I kind.I letter.I
 */
const fs = require('node:fs');
const path = require('node:path');

const SHIP = ['seen', 'unseen', 'none'];
const TOKENS = { N: 5, n: 1, t: 2 };
const LIMIT = { wx: 40, lamp: 38, ship: 70, letter: 140, name: 17, time: 18, kind: 28 };
const BOAT = 'The oil boat came.';
const BODY = 4 * 47;            // four lines of 47 columns in the book

function parse(text) {
    const words = { wx: [], lamp: [], ship: [], name: [], time: [], kind: [], letter: [] };
    const want = { wx: 24, lamp: 16, ship: 12, name: 6, time: 3, kind: 6, letter: 6 };
    text.split('\n').forEach((line, i) => {
        if (/^\s*(#|$)/.test(line)) return;
        const m = /^([a-z]+)\.([a-z0-9.]+): (.*)$/.exec(line);
        if (!m) throw new Error(`words.txt:${i + 1}: not "key: text"`);
        const [, kind, key, s] = m;
        if (!words[kind]) throw new Error(`words.txt:${i + 1}: unknown kind ${kind}`);
        if (/"/.test(s)) throw new Error(`words.txt:${i + 1}: no double quotes`);
        const parts = key.split('.');
        let idx;
        if (kind === 'wx' || kind === 'lamp') idx = (+parts[0]) * 4 + (+parts[1]);
        else if (kind === 'ship') idx = SHIP.indexOf(parts[0]) * 4 + (+parts[1]);
        else idx = +parts[0];
        if (!(idx >= 0) || idx >= want[kind]) throw new Error(`words.txt:${i + 1}: bad key ${kind}.${key}`);
        if (words[kind][idx] !== undefined) throw new Error(`words.txt:${i + 1}: ${kind}.${key} twice`);
        for (const t of s.matchAll(/\{(.)\}/g)) if (!(t[1] in TOKENS)) throw new Error(`words.txt:${i + 1}: unknown token {${t[1]}}`);
        if (/\\/.test(s)) throw new Error(`words.txt:${i + 1}: no backslashes`);
        words[kind][idx] = s;
    });
    for (const k of Object.keys(want)) {
        for (let i = 0; i < want[k]; i++) if (words[k][i] === undefined) throw new Error(`words.txt: ${k} ${i} is missing`);
    }
    return words;
}

function expandShip(words, tpl, shp, slt) {
    return tpl.replace(/\{(.)\}/g, (_, t) => {
        if (t === 't') return words.time[slt];
        const nm = words.name[shp];
        return t === 'N' ? nm[0].toUpperCase() + nm.slice(1) : nm;
    });
}

function check(words) {
    const mx = a => Math.max(...a.map(s => s.length));
    for (const k of ['wx', 'lamp', 'letter', 'name', 'time', 'kind']) {
        for (const s of words[k]) if (s.length > LIMIT[k]) throw new Error(`${k}: "${s}" is ${s.length}, over ${LIMIT[k]}`);
    }
    let ship = 0;
    for (let sh = 0; sh < 6; sh++) for (let sl = 0; sl < 3; sl++) for (const t of words.ship) ship = Math.max(ship, expandShip(words, t, sh, sl).length);
    if (ship > LIMIT.ship) throw new Error(`a ship line is ${ship}, over ${LIMIT.ship}`);
    const worst = 'Night 9999. '.length + mx(words.wx) + 1 + mx(words.lamp) + 1 + ship + 1 + BOAT.length;
    if (worst > BODY - 12) throw new Error(`the worst entry is ${worst} characters; the book holds ${BODY - 12}`);
    return { worst, ship };
}

const q = s => s.replace(/\{(.)\}/g, (_, t) => `",${TOKENS[t]},"`);
const line = s => `db "${q(s)}",0`.replace(/"",/g, '').replace(/,""/g, '');

function build(text) {
    const words = parse(text);
    check(words);
    const out = ['; words.inc: generated by mkwords.js from words.txt. Do not edit.'];
    const table = (label, prefix, arr) => {
        out.push(`${label}: dw ${arr.map((_, i) => `${prefix}${i}`).join(',')}`);
    };
    table('wxtab', 'wx_', words.wx);
    table('lamptab', 'lm_', words.lamp);
    table('shiptab', 'sh_', words.ship);
    table('nametab', 'nm_', words.name);
    table('timetab', 'tm_', words.time);
    table('kindtab', 'kd_', words.kind);
    table('lettab', 'lt_', words.letter);
    const body = (prefix, arr) => arr.forEach((s, i) => out.push(`${prefix}${i}: ${line(s)}`));
    body('wx_', words.wx); body('lm_', words.lamp); body('sh_', words.ship); body('nm_', words.name);
    body('tm_', words.time); body('kd_', words.kind); body('lt_', words.letter);
    return out.join('\n') + '\n';
}

module.exports = { parse, build, check, expandShip, BOAT };

if (require.main === module) {
    const dir = __dirname;
    const text = fs.readFileSync(path.join(dir, 'words.txt'), 'utf8');
    fs.writeFileSync(path.join(dir, 'words.inc'), build(text));
}
